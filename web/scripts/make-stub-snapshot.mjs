#!/usr/bin/env node
/**
 * Generates FAKE stub data in public/snapshot/ so `VITE_STATIC=1 npm run dev` works
 * before Backend is ready. Every number and polygon here is made up.
 *
 * Replace the whole folder with Backend's real snapshot export (same file names) before
 * any demo or the Vercel backup build. Run: node scripts/make-stub-snapshot.mjs
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { deflateSync } from 'node:zlib'

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'snapshot')
const YEAR = 2022
const AS_OF = ['2022-08-12', '2022-09-12', '2022-10-12', '2022-11-12']
const STUB = 'FAKE STUB DATA — generated by web/scripts/make-stub-snapshot.mjs; replace with Backend snapshot'

// ---------- deterministic RNG ----------
let seed = 20221012
const rand = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 2 ** 32)
const between = (a, b) => a + (b - a) * rand()
const round = (x, d = 3) => Math.round(x * 10 ** d) / 10 ** d

const doy = (iso) => {
  const d = new Date(`${iso}T00:00:00Z`)
  return Math.floor((d - Date.UTC(d.getUTCFullYear(), 0, 0)) / 864e5)
}
const isoFromDoy = (day) => new Date(Date.UTC(YEAR, 0, day)).toISOString().slice(0, 10)

// ---------- fields: 83 fake quadrilaterals around Beltsville ----------
const CENTER = [39.03, -76.9]
const COLS = 10
const fields = []
for (let i = 0; i < 83; i++) {
  const r = Math.floor(i / COLS)
  const c = i % COLS
  const lat0 = CENTER[0] + 0.019 - r * 0.0048 + between(-0.0006, 0.0006)
  const lon0 = CENTER[1] - 0.027 + c * 0.0058 + between(-0.0008, 0.0008)
  const h = between(0.0022, 0.0036)
  const w = between(0.0030, 0.0046)
  const j = () => between(-0.00035, 0.00035)
  const ring = [
    [lon0 + j(), lat0 + j()],
    [lon0 + w + j(), lat0 + j()],
    [lon0 + w + j(), lat0 - h + j()],
    [lon0 + j(), lat0 - h + j()],
  ].map(([x, y]) => [round(x, 6), round(y, 6)])
  ring.push(ring[0])
  const isSilage = rand() < 0.27
  const insufficient = rand() < 0.05
  const harvest = isSilage ? Math.round(between(doy('2022-08-22'), doy('2022-09-14'))) : Math.round(between(doy('2022-10-01'), doy('2022-11-08')))
  const declineStart = isSilage ? harvest : harvest - Math.round(between(18, 32))
  fields.push({ id: 1000 + i, ring, isSilage, insufficient, harvest, declineStart, acres: round(between(8, 42), 1) })
}

// 15 labeled field-years in 2022 (fake): 11 grain, 4 silage
const labeled = new Set()
const grains = fields.filter((f) => !f.isSilage && !f.insufficient)
const silages = fields.filter((f) => f.isSilage && !f.insufficient)
grains.slice(0, 11).forEach((f) => labeled.add(f.id))
silages.slice(0, 4).forEach((f) => labeled.add(f.id))
// two deliberate model mistakes so the map shows fill/outline disagreement
const wrong = new Set([grains[2].id, silages[1].id])

// ---------- write helpers ----------
mkdirSync(OUT, { recursive: true })
for (const name of readdirSync(OUT)) {
  if (name.endsWith('.json') || name.endsWith('.csv') || name === 'chips') rmSync(join(OUT, name), { recursive: true, force: true })
}
mkdirSync(join(OUT, 'chips'), { recursive: true })
const write = (name, data) => writeFileSync(join(OUT, `${name}.json`), JSON.stringify(data, null, 1))

write('_meta', { stub: true, note: STUB, years: [YEAR], as_of_dates: AS_OF })

write(`fields_${YEAR}`, {
  type: 'FeatureCollection',
  _stub: STUB,
  features: fields.map((f) => ({
    type: 'Feature',
    properties: {
      OBJECTID: f.id,
      label: labeled.has(f.id) ? (f.isSilage ? 'Silage' : 'Grain') : null,
      ACRES: f.acres,
      FIELD: `STUB-${f.id}`,
    },
    geometry: { type: 'Polygon', coordinates: [f.ring] },
  })),
})

// ---------- predictions per as-of date ----------
const features = (f, p) => {
  const s = p >= 0.5 ? 1 : -1
  return JSON.stringify([
    { name: 'ndvi_pre_drop', value: round(f.isSilage ? between(0.72, 0.86) : between(0.38, 0.55), 2), contrib: round(s * between(0.7, 1.1), 2) },
    { name: 'drop_days', value: Math.round(f.isSilage ? between(4, 9) : between(18, 35)), contrib: round(s * between(0.4, 0.8), 2) },
    { name: 'ndti_post', value: round(f.isSilage ? between(0.03, 0.07) : between(0.11, 0.18), 3), contrib: round(s * between(0.3, 0.6), 2) },
    { name: 'decline_doy_rel', value: Math.round(f.isSilage ? between(-45, -25) : between(-8, 10)), contrib: round(s * between(0.2, 0.45), 2) },
    { name: 'dairy_dist_km', value: round(between(1, 14), 1), contrib: round(between(-0.15, 0.15), 2) },
  ])
}
for (const asOf of AS_OF) {
  const cut = doy(asOf)
  write(
    `predict_${YEAR}_${asOf}`,
    fields.map((f) => {
      const base = { OBJECTID: f.id, year: YEAR, as_of: asOf }
      if (f.insufficient) return { ...base, p_silage: null, class: 'Insufficient', abstain: true, top_features: '[]' }
      if (f.harvest > cut) return { ...base, p_silage: null, class: 'Pending', abstain: false, top_features: '[]' }
      let p = f.isSilage ? between(0.74, 0.97) : between(0.03, 0.28)
      if (wrong.has(f.id)) p = 1 - p
      p = round(p, 2)
      return { ...base, p_silage: p, class: p >= 0.5 ? 'Silage' : 'Grain', abstain: false, top_features: features(f, p) }
    }),
  )
}

// ---------- evaluation (fake numbers, plausible for 44 labeled field-years) ----------
const wilson = (k, n, z = 1.96) => {
  const p = k / n
  const d = 1 + (z * z) / n
  const c = (p + (z * z) / (2 * n)) / d
  const h = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / d
  return { value: round(p), lo: round(c - h), hi: round(c + h) }
}
const cm = [
  [28, 3],
  [2, 9],
]
write('evaluate_strict', {
  _stub: STUB,
  split: 'strict',
  labels: ['Grain', 'Silage'],
  confusion: cm,
  per_class: {
    Grain: { precision: wilson(28, 30), recall: wilson(28, 31), support: 31 },
    Silage: { precision: wilson(9, 12), recall: wilson(9, 11), support: 11 },
  },
  convergence: [
    { as_of: AS_OF[0], share_decided: 0.04, acc_decided: 1.0 },
    { as_of: AS_OF[1], share_decided: 0.31, acc_decided: 0.86 },
    { as_of: AS_OF[2], share_decided: 0.64, acc_decided: 0.89 },
    { as_of: AS_OF[3], share_decided: 0.95, acc_decided: 0.88 },
  ],
  abstained: 2,
  n_evaluated: 42,
})

// ---------- Maryland roll-up ----------
write(`rollup_${YEAR}`, {
  _stub: STUB,
  year: YEAR,
  region: 'Maryland',
  acres: 64800,
  ci: [55100, 74600],
  cv_pct: 7.6,
  census_acres: 61200,
  csv_url: `rollup_${YEAR}.csv`,
})
writeFileSync(
  join(OUT, `rollup_${YEAR}.csv`),
  [
    'year,aggregation_level,state_name,county_name,commodity,crop_use,statistic,unit,value,cv_percent,source',
    `${YEAR},STATE,MARYLAND,,CORN,silage,AREA HARVESTED,ACRES,64800,7.6,FAKE STUB - not real`,
    `${YEAR},COUNTY,MARYLAND,FREDERICK,CORN,silage,AREA HARVESTED,ACRES,14100,11.2,FAKE STUB - not real`,
    `${YEAR},COUNTY,MARYLAND,CARROLL,CORN,silage,AREA HARVESTED,ACRES,9800,12.9,FAKE STUB - not real`,
    `${YEAR},COUNTY,MARYLAND,WASHINGTON,CORN,silage,AREA HARVESTED,ACRES,9200,13.4,FAKE STUB - not real`,
    '',
  ].join('\n'),
)

// ---------- per-field NDVI / NDTI series ----------
const smooth = (x) => 1 / (1 + Math.exp(-x))
for (const f of fields) {
  const points = []
  for (let d = doy('2022-05-20'); d <= doy('2022-11-28'); d += Math.round(between(4, 7))) {
    const cloudy = rand() < (f.insufficient ? 0.55 : 0.18)
    const greenUp = smooth((d - doy('2022-06-20')) / 7)
    let ndvi = 0.18 + 0.68 * greenUp
    let ndti = 0.08 + 0.14 * greenUp
    if (d >= f.declineStart) {
      if (f.isSilage) {
        ndvi = 0.16 + between(0, 0.04)
        ndti = 0.04 + between(0, 0.02)
      } else if (d < f.harvest) {
        const t = (d - f.declineStart) / (f.harvest - f.declineStart)
        ndvi = 0.86 - 0.5 * t
        ndti = 0.22 - 0.06 * t
      } else {
        ndvi = 0.24 + between(0, 0.04)
        ndti = 0.14 + between(0, 0.03)
      }
    }
    points.push({
      date: isoFromDoy(d),
      ndvi: cloudy ? null : round(ndvi + between(-0.025, 0.025)),
      ndti: cloudy ? null : round(ndti + between(-0.012, 0.012)),
    })
  }
  write(`series_${f.id}_${YEAR}`, {
    _stub: STUB,
    OBJECTID: f.id,
    year: YEAR,
    points,
    decline_date: f.insufficient ? null : isoFromDoy(f.declineStart),
  })
}

// ---------- image chips (tiny procedural PNGs, clearly not real imagery) ----------
const crcTable = Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})
const crc32 = (buf) => {
  let c = 0xffffffff
  for (const b of buf) c = crcTable[(c ^ b) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
const chunk = (type, data) => {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([len, body, crc])
}
const png = (size, pixel) => {
  const raw = Buffer.alloc((size * 3 + 1) * size)
  for (let y = 0; y < size; y++) {
    raw[y * (size * 3 + 1)] = 0
    for (let x = 0; x < size; x++) {
      const [r, g, b] = pixel(x, y)
      const o = y * (size * 3 + 1) + 1 + x * 3
      raw[o] = r
      raw[o + 1] = g
      raw[o + 2] = b
    }
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(size, 0)
  ihdr.writeUInt32BE(size, 4)
  ihdr[8] = 8
  ihdr[9] = 2
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ])
}
const SIZE = 96
for (const f of fields) {
  const rows = (x, y) => (x + y) % 6 < 3
  const pre = (x, y) => (rows(x, y) ? [46, 110, 52] : [64, 132, 66])
  const post = f.isSilage
    ? (x, y) => (rows(x, y) ? [92, 70, 52] : [104, 80, 60]) // bare dark soil, faint rows
    : (x, y) => (rows(x, y) ? [176, 146, 98] : [150, 120, 80]) // tan residue blanket
  writeFileSync(join(OUT, 'chips', `${f.id}_${YEAR}_pre.png`), png(SIZE, pre))
  writeFileSync(join(OUT, 'chips', `${f.id}_${YEAR}_post.png`), png(SIZE, post))
}

// ---------- agent run + trace ----------
write('agent_run', { run_id: 'stub' })
const t = (step, node, type, tool, args, summary) => ({ step, node, type, tool, args, summary })
write('agent_trace_stub', {
  _stub: STUB,
  run_id: 'stub',
  status: 'done',
  lines: [
    t(1, 'Analyst', 'plan', null, null, 'Plan: load BARC 2022 fields → series as of 2022-10-12 → classify → score vs labels → Maryland roll-up vs Census 2022.'),
    t(2, 'Analyst', 'tool_call', 'get_fields', { year: 2022 }, '83 fields loaded (15 labeled).'),
    t(3, 'Analyst', 'tool_call', 'get_timeseries', { year: 2022, as_of: '2022-10-12' }, 'Series built for 83 fields; median 24 clear looks per field.'),
    t(4, 'Verifier', 'flag', null, { fields: [1007, 1031, 1052, 1066] }, '4 fields have fewer than 8 clear looks in Aug–Sep. Requesting more imagery before classifying them.'),
    t(5, 'Analyst', 'tool_call', 'get_timeseries', { fields: [1007, 1031, 1052, 1066], sensors: ['HLS'] }, 'HLS added 9 looks; 2 fields still insufficient → will abstain.'),
    t(6, 'Analyst', 'tool_call', 'classify', { year: 2022, as_of: '2022-10-12' }, '53 decided (14 silage, 39 grain), 28 pending, 2 abstained.'),
    t(7, 'Analyst', 'tool_call', 'evaluate', { split: 'strict' }, 'Held-out 2022: silage recall 0.82 [0.52, 0.95], precision 0.75 [0.47, 0.91].'),
    t(8, 'Verifier', 'flag', null, { field: 1004 }, 'Field 1004 called Silage but its NDTI after the drop looks like residue (0.15). Marking as a likely error.'),
    t(9, 'Analyst', 'tool_call', 'aggregate', { region: 'Maryland', year: 2022 }, 'Maryland silage 64,800 ac [55,100, 74,600], CV 7.6%.'),
    t(10, 'Analyst', 'tool_call', 'get_quickstats', { year: 2022, crop_use: 'silage', state: 'MD' }, 'Census 2022 Maryland silage: 61,200 ac.'),
    t(11, 'Verifier', 'observation', null, null, 'Census value falls inside our interval. All numbers in the draft trace to a tool call.'),
    t(12, 'Writer', 'report', 'write_report', { format: 'markdown' }, 'Report written: metrics, 2 flagged fields, Maryland roll-up vs Census, limitations.'),
  ],
})

console.log(`Wrote FAKE stub snapshot to ${OUT}`)
