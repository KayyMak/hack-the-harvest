def _norm(token: str) -> str:
    t = token.replace(',', '').rstrip('.')
    if '.' not in t:
        t = t.lstrip('0') or '0'
    return t


def _numbers(text: str) -> set[str]:
    return {_norm(t) for t in NUM.findall(text)}


def _claims_with_line_citations(markdown: str) -> list[tuple[str, list[str]]]:
    """Sentences and bullet items (headings skipped), each with the citations found on its line.
    A trailing citation-only fragment joins the previous claim."""
    out = []
    for raw in markdown.split('\n'):
        line = raw.strip()
        if not line or re.match(r'^#{1,6}\s', line) or re.fullmatch(r'[-*_]{3,}', line):
            continue
        line = re.sub(r'^(?:[-*•]|\d+\.)\s+', '', line)
        line_cites = CITE.findall(line)
        for part in re.split(r'(?<=[.!?])\s+(?=[A-Z(\[*])', line):
            part = part.strip()
            if not part:
                continue
            if out and re.fullmatch(r'(?:\[[^\]]+\][\s.,;]*)+', part):
                out[-1] = (out[-1][0] + ' ' + part, out[-1][1])
            else:
                out.append((part, line_cites))
    return out


def claims(markdown: str) -> list[str]:
    return [c for c, _ in _claims_with_line_citations(markdown)]


def _resolve_cites(cited: list[str], sources: dict[str, str]) -> list[str]:
    """A bare tool name (e.g. [model_field_calls]) cites every result of that tool retrieved in this run."""
    out = []
    for c in cited:
        if c in sources:
            out.append(c)
        else:
            out += [sid for sid in sources if sid.startswith(c + '.')] or [c]
    return out


def check_grounding(markdown: str, sources: dict[str, str], always_ok: frozenset[str] = frozenset()) -> list[dict]:
    """sources maps citable id -> the text that id returned. Returns the claims that fail.
    always_ok: numbers allowed without support (only the report's own year)."""
    bad = []
    for claim, line_cites in _claims_with_line_citations(markdown):
        # A sentence without its own citation may borrow its line's citations only when it states numbers
        # (which must then appear in those sources). A number-free sentence needs its own citation, so
        # uncited general statements can't ride along next to a cited one.
        cited = CITE.findall(claim)
        if not cited and line_cites and _numbers(claim):
            cited = line_cites
        if not cited:
            bad.append({'text': claim, 'kind': 'uncited', 'reason': 'no citation'})
            continue
        cited = _resolve_cites(cited, sources)
        unknown = [c for c in cited if c not in sources]
        if unknown:
            bad.append({'text': claim, 'kind': 'unsupported', 'reason': 'cites a source not retrieved in this run: ' + ', '.join(unknown)})
            continue
        body = CITE.sub(' ', claim)
        support = set().union(*(_numbers(sources[c]) for c in cited))
        missing = sorted(_numbers(body) - support - always_ok, key=len)
        if not missing:
            continue
        elsewhere = {n: [sid for sid, txt in sources.items() if n in _numbers(txt)][:2] or None for n in missing}
        nowhere = [n for n, sid in elsewhere.items() if sid is None]
        if nowhere:
            bad.append({'text': claim, 'kind': 'unsupported',
                        'reason': 'numbers not found in any retrieved data: ' + ', '.join(nowhere)})
        else:
            bad.append({'text': claim, 'kind': 'miscited',
                        'found_in': sorted({x for sids in elsewhere.values() for x in sids}),
                        'reason': 'correct figure, wrong citation: ' + ', '.join(
                            f'{n} is in ' + ' and '.join(f'[{x}]' for x in sids) for n, sids in elsewhere.items())})
    return bad


