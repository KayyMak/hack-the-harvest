# ---------------------------------------------------------------- configuration

@dataclass(frozen=True)
class Config:
    key: str
    base_url: str
    model: str
    thinking: bool


def _env_file() -> dict[str, str]:
    values = {}
    try:
        lines = ENV_FILE.read_text(encoding='utf-8').splitlines()
    except OSError:
        return values
    for line in lines:
        line = line.strip()
        if not line or line.startswith('#') or '=' not in line:
            continue
        k, v = line.split('=', 1)
        values[k.strip()] = v.strip().strip('"').strip("'")
    return values


def config() -> Config:
    """Process environment wins (hosting), then the repo-root .env file (local)."""
    file = _env_file()
    get = lambda k, d='': (os.environ.get(k) or file.get(k) or d).strip()  # noqa: E731
    return Config(key=get('NVIDIA_API_KEY'), base_url=get('NEMOTRON_BASE_URL', DEFAULT_BASE).rstrip('/'),
                  model=get('NEMOTRON_MODEL', DEFAULT_MODEL), thinking=get('NEMOTRON_THINKING', 'false').lower() == 'true')


def status() -> dict:
    c = config()
    return {'configured': bool(c.key), 'model': c.model,
            'how_to_configure': 'Add NVIDIA_API_KEY=... to the .env file in the repository root (see .env.example).'}


# ---------------------------------------------------------------- formatting helpers

def _int(x): return f'{round(x):,}'
def _usd(x): return f'${round(x):,}'
def _pct(x, d=1): return f'{x * 100:.{d}f}%'
def _pp(x): return f'{x * 100:+.1f} percentage points'


def _nass(year: int) -> dict:
    try:
        with NASS_CSV.open(encoding='utf-8', newline='') as f:
            rows = [r for r in csv.DictReader(f) if int(r['year']) == year]
    except (OSError, ValueError, KeyError) as exc:
        raise ArtifactUnavailable('NASS market table (market/data/nass_market.csv) is missing; '
                                  'run python market/fetch_nass.py.') from exc
    if not rows:
        raise ArtifactUnavailable(f'No NASS market rows for {year}.')
    d = {}
    for r in rows:
        key = ('md_' if r['geo'] == 'Maryland' else 'us_') + r['item']
        d[key] = float(r['value']) if r['value'] else None
        if r['item'] == 'grain_price':
            d[key + '_preliminary'] = r['preliminary'] == 'True'
    return d


def _sources() -> dict:
    try:
        nass = json.loads(NASS_SOURCES.read_text(encoding='utf-8'))
    except (OSError, ValueError):
        nass = {}
    return {k: f"USDA NASS {v['title']} (released {v['released']})" for k, v in nass.items()}


def _check_year(year, allowed=YEARS) -> int:
    year = int(year)
    if year not in allowed:
        raise ValueError(f'year must be one of {list(allowed)}')
    return year


def _labels_known(year: int) -> bool:
    """BARC reference labels (ground truth) only exist after harvest; hide them in in-season outlooks."""
    as_of = _AS_OF.get()
    return as_of is None or as_of >= date(year, 12, 31)


LABEL_NOTE = 'BARC reference labels are not known yet on this date (they are recorded after harvest).'
ACCURACY_NOTE = ('The model\'s held-out accuracy is withheld until after harvest: it is computed from the BARC '
                 'reference labels of 2021-2023, not all of which are known on this date.')
DOCS_NOTE = ('Project results are hidden for in-season runs: only methods and data-source documents are searched, '
             'because the other documents report results computed from BARC labels recorded after harvest.')


def _results_known() -> bool:
    """Project results (accuracy figures, model review, experiments) are computed from the 2021-2023 BARC
    labels, so they count as known only on a post-season date (Dec 31) from the 2023 harvest on, or with no
    as-of date at all. Any in-season date (before Dec 31 of its year) hides them."""
    as_of = _AS_OF.get()
    return as_of is None or (_labels_known(as_of.year) and _labels_known(max(YEARS)))


def _doc_sources() -> tuple[str, ...] | None:
    """Documents a report may search on its date: all of them, or in-season only the methods allow-list."""
    return None if _results_known() else docsearch.IN_SEASON_SAFE


def _points_known(year: int):
    """Saved model calls for a season, up to the as-of date."""
    as_of = _AS_OF.get()
    pts = [p for p in _convergence(year) if as_of is None or p.as_of <= as_of]
    if not pts:
        raise ValueError(f'the model had made no calls for {year} as of {as_of}; its first call is on {year}-08-12.')
    return pts


def _convergence(year: int):
    conv = next((y for y in artifacts.compute_convergence().years if y.year == year), None)
    if conv is None or not conv.points:
        raise ArtifactUnavailable(f'No saved model predictions for {year}.')
    return conv.points


