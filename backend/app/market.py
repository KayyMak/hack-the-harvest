def maryland_supply(year: int) -> dict:
    """Official NASS Maryland corn split for the year, and the grain that silage acres displaced."""
    year = _check_year(year, NASS_YEARS)
    _known_by(_nass_published(year), f'Official NASS figures for {year}')
    n = _nass(year)
    grain, silage = n['md_grain_area_harvested'] * 1000, n['md_silage_area_harvested'] * 1000
    total = grain + silage
    forgone = silage * n['md_grain_yield']
    prelim = ' (preliminary)' if n['md_grain_price_preliminary'] else ''
    return {
        'year': year, 'source': f'USDA NASS Crop Production and Crop Values annual summaries for {year} (published early {year + 1})',
        'maryland_corn_acres_planted_all_purposes': _int(n['md_planted_all_purposes'] * 1000),
        'maryland_grain_acres_harvested': _int(grain), 'maryland_silage_acres_harvested': _int(silage),
        'maryland_corn_acres_harvested_grain_plus_silage': _int(total),
        'maryland_silage_share_of_harvested_corn': _pct(silage / total),
        'maryland_grain_share_of_harvested_corn': _pct(grain / total),
        'maryland_grain_yield': f"{n['md_grain_yield']:.0f} bu/acre",
        'maryland_silage_yield': f"{n['md_silage_yield']:.0f} tons/acre",
        'maryland_grain_production_bushels': _int(n['md_grain_production'] * 1000),
        'maryland_silage_production_tons': _int(n['md_silage_production'] * 1000),
        'maryland_grain_price_received': f"${n['md_grain_price']:.2f}/bu{prelim}",
        'us_grain_price_received': f"${n['us_grain_price']:.2f}/bu{prelim}",
        'us_grain_production_bushels': _int(n['us_grain_production'] * 1000),
        'maryland_share_of_us_grain_production': _pct(n['md_grain_production'] / n['us_grain_production']),
        'grain_bushels_not_produced_because_of_silage_acres': _int(forgone),
        'value_of_those_bushels_at_maryland_price': _usd(forgone * n['md_grain_price']),
        'notes': 'Acre figures are HARVESTED acres unless labeled planted. NASS publishes no silage price, '
                 'so silage is reported in tons only. These are official statistics, not model output.',
    }


def barc_predictions(year: int) -> dict:
    """The prediction model's latest silage estimate at BARC (as of the report date). After harvest also
    BARC's reference labels and the model's held-out accuracy; both are withheld for in-season dates."""
    year = _check_year(year)
    p = _points_known(year)[-1]
    lo, hi = p.expected_silage_acres_95ci
    tot = p.total_acres
    out = {
        'year': year, 'scope': 'Labeled BARC research fields only (Beltsville, MD); NOT a Maryland estimate',
        'as_of': str(p.as_of), 'labeled_field_years': p.field_years, 'barc_corn_acres': _int(tot),
        'model_expected_silage_acres': _int(p.expected_silage_acres),
        'model_expected_grain_acres': _int(tot - p.expected_silage_acres),
        'model_95pct_range_silage_acres': f'{_int(lo)} to {_int(hi)}',
        'reference_silage_acres_from_barc_labels': _int(p.reference_silage_acres),
        'reference_grain_acres_from_barc_labels': _int(tot - p.reference_silage_acres),
        'model_silage_share': _pct(p.expected_silage_acres / tot),
        'reference_silage_share': _pct(p.reference_silage_acres / tot),
        'model_error_in_silage_share': _pp((p.expected_silage_acres - p.reference_silage_acres) / tot),
    }
    if _results_known():
        summary = artifacts.read_summary()
        s = summary.logistic
        out['model_reliability_all_years'] = {
            'held_out_field_years': summary.evaluated_field_years,
            'silage_field_years': sum(s.confusion_matrix[s.matrix_order.index('Silage')]),
            'silage_field_years_caught': s.confusion_matrix[1][1],
            'silage_field_years_missed': s.confusion_matrix[1][0],
            'grain_field_years_called_silage': s.confusion_matrix[0][1],
            'silage_recall': _pct(s.silage_recall), 'silage_precision': _pct(s.silage_precision),
            'balanced_accuracy': _pct(s.balanced_accuracy),
            'decision_rule': 'a field is called Silage when its silage probability is at least 0.5',
            'note': 'Field-held-out validation at one site (2021-2023, computed after those seasons); small sample, wide uncertainty.'}
    else:
        out['model_reliability'] = ACCURACY_NOTE
    if not _labels_known(year):
        for k in ('reference_silage_acres_from_barc_labels', 'reference_grain_acres_from_barc_labels',
                  'reference_silage_share', 'model_error_in_silage_share'):
            out.pop(k)
        out['labels'] = LABEL_NOTE
    return out


def season_convergence(year: int) -> dict:
    """How the model's BARC silage estimate changes through the season (up to the as-of date), trend spelled out."""
    year = _check_year(year)
    pts = _points_known(year)
    rows = []
    for p in pts:
        lo, hi = p.expected_silage_acres_95ci
        rows.append({'as_of': str(p.as_of), 'fields_decided': p.field_years,
                     'expected_silage_acres': _int(p.expected_silage_acres),
                     'range_95pct': f'{_int(lo)} to {_int(hi)}', 'range_width_acres': _int(hi - lo),
                     'reference_silage_acres': _int(p.reference_silage_acres)})
    first, last = pts[0], pts[-1]
    w0 = first.expected_silage_acres_95ci[1] - first.expected_silage_acres_95ci[0]
    w1 = last.expected_silage_acres_95ci[1] - last.expected_silage_acres_95ci[0]
    peak = max(pts, key=lambda p: p.expected_silage_acres)
    closest = min(pts, key=lambda p: abs(p.expected_silage_acres - p.reference_silage_acres))
    ref = last.reference_silage_acres
    direction = 'narrowed' if w1 < w0 else 'widened' if w1 > w0 else 'stayed the same width'
    if not _labels_known(year):
        for r in rows:
            r.pop('reference_silage_acres')
        return {'year': year, 'scope': 'Labeled BARC fields only', 'points': rows, 'labels': LABEL_NOTE,
                'trend': {'first_estimate': f'{_int(first.expected_silage_acres)} acres on {first.as_of}',
                          'latest_estimate': f'{_int(last.expected_silage_acres)} acres on {last.as_of}',
                          'highest_estimate': f'{_int(peak.expected_silage_acres)} acres on {peak.as_of}',
                          'range_width_change': f'the 95% range {direction}, from {_int(w0)} acres wide on {first.as_of} '
                                                f'to {_int(w1)} acres wide on {last.as_of}'}}
    return {
        'year': year, 'scope': 'Labeled BARC fields only', 'points': rows,
        'trend': {
            'first_estimate': f'{_int(first.expected_silage_acres)} acres on {first.as_of}',
            'final_estimate': f'{_int(last.expected_silage_acres)} acres on {last.as_of}',
            'highest_estimate': f'{_int(peak.expected_silage_acres)} acres on {peak.as_of}',
            'closest_to_reference': f'{_int(closest.expected_silage_acres)} acres on {closest.as_of} '
                                    f'(reference {_int(ref)} acres)',
            'range_width_change': f'the 95% range {direction}, from {_int(w0)} acres wide on {first.as_of} '
                                  f'to {_int(w1)} acres wide on {last.as_of}',
            'final_vs_reference': f'final estimate is {_int(abs(last.expected_silage_acres - ref))} acres '
                                  f'{"below" if last.expected_silage_acres < ref else "above"} the reference',
        },
        'official_numbers_published': 'NASS publishes final silage acres in its Crop Production Annual '
                                      'Summary in January of the following year (2023 crop: January 12, 2024).',
    }


def model_field_calls(year: int, month_day: str = '11-30') -> dict:
    """The model's own inference for every labeled BARC field on a saved date: probability, call, label."""
    year = _check_year(year)
    if month_day not in MONTH_DAYS:
        raise ValueError(f'month_day must be one of {list(MONTH_DAYS)}')
    _known_by(date.fromisoformat(f'{year}-{month_day}'), f'The model call for {year}-{month_day}')
    entry = next((d for d in artifacts.read_asof().dates if d.year == year and str(d.as_of)[5:] == month_day), None)
    if entry is None:
        raise ArtifactUnavailable(f'No saved model calls for {year}-{month_day}.')
    acres = {f.field_id: f.acres for f in artifacts.read_fields()}
    missing = sorted({p.field_id for p in entry.predictions if acres.get(p.field_id) is None})
    if missing:  # never report a silent 0 acres
        raise ArtifactUnavailable(f'No acreage for field(s) {missing} in the saved field table; rebuild the baseline outputs.')
    fields = [{'field_id': p.field_id, 'acres': f'{acres[p.field_id]:.1f}',
               'silage_probability': _pct(p.silage_probability, 0), 'model_call': p.predicted_label,
               'barc_label': p.reference_label, 'agrees_with_label': p.predicted_label == p.reference_label}
              for p in sorted(entry.predictions, key=lambda p: -p.silage_probability)]
    if not _labels_known(year):
        for f in fields:
            f.pop('barc_label')
            f.pop('agrees_with_label')
        return {'year': year, 'as_of': str(entry.as_of), 'model_mode': entry.mode, 'features_used': entry.features,
                'fields_called': len(fields), 'fields_pending': len(entry.pending_field_ids),
                'calls_silage': sum(f['model_call'] == 'Silage' for f in fields),
                'calls_grain': sum(f['model_call'] == 'Grain' for f in fields),
                'fields': fields, 'labels': LABEL_NOTE,
                'note': 'Held-out predictions: each field was scored by a model that did not train on it.'}
    agree = sum(f['agrees_with_label'] for f in fields)
    return {
        'year': year, 'as_of': str(entry.as_of), 'model_mode': entry.mode, 'features_used': entry.features,
        'fields_called': len(fields), 'fields_pending': len(entry.pending_field_ids),
        'calls_silage': sum(f['model_call'] == 'Silage' for f in fields),
        'calls_grain': sum(f['model_call'] == 'Grain' for f in fields),
        'agreeing_with_barc_labels': f'{agree} of {len(fields)}',
        'disagreeing_fields': [f"field {f['field_id']}: model {f['model_call']} at {f['silage_probability']} silage "
                               f"probability, BARC label {f['barc_label']}" for f in fields if not f['agrees_with_label']],
        'fields': fields,
        'note': 'Held-out predictions: each field was scored by a model that did not train on it.',
    }


def price_effect(year: int, scenario: str) -> dict:
    """National corn price effect of a Maryland supply change, for an assumed elasticity range."""
    year = _check_year(year, NASS_YEARS)
    _known_by(_nass_published(year), f'Official NASS figures for {year}')
    n = _nass(year)
    harvested = (n['md_grain_area_harvested'] + n['md_silage_area_harvested']) * 1000
    yld = n['md_grain_yield']
    if scenario == 'one_point_of_maryland_silage_share':
        bushels, label = harvested * 0.01 * yld, 'Maryland silage share 1 percentage point higher'
    elif scenario == 'all_maryland_silage_harvested_as_grain':
        bushels, label = n['md_silage_area_harvested'] * 1000 * yld, 'every Maryland silage acre harvested as grain instead'
    elif scenario == 'barc_model_error_applied_statewide':
        p = _points_known(_check_year(year))[-1]
        err = abs(p.expected_silage_acres - p.reference_silage_acres) / p.total_acres
        bushels, label = harvested * err * yld, f'the model\'s BARC share error ({err * 100:.1f} percentage points) applied statewide'
    else:
        raise ValueError('scenario must be one_point_of_maryland_silage_share, '
                         'all_maryland_silage_harvested_as_grain or barc_model_error_applied_statewide')
    pct_supply = bushels / (n['us_grain_production'] * 1000)
    return {
        'year': year, 'scenario': label, 'grain_bushels_shifted': _int(bushels),
        'maryland_grain_price_received': f"${n['md_grain_price']:.2f}/bu",
        'value_at_maryland_price': _usd(bushels * n['md_grain_price']),
        'maryland_share_of_us_grain_production': _pct(n['md_grain_production'] / n['us_grain_production']),
        'share_of_us_grain_supply': _pct(pct_supply, 3),
        'us_price_effect_by_assumed_elasticity': [
            {'elasticity': f'-{e}', 'meaning': ELASTICITY_MEANING[e], 'price_change': _pct(pct_supply / e, 3),
             'cents_per_bushel': f'{pct_supply / e * n["us_grain_price"] * 100:.2f} cents/bu'} for e in ELASTICITIES],
        'assumption': 'Price change = supply change / |elasticity|. The elasticity range is an assumption '
                      '(no single sourced estimate); ignores stocks, trade and futures markets.',
    }


def planting_outlook() -> dict:
    """What Maryland grows: NASS harvested grain vs silage acres for published years, and the 2025 outlook
    as known on the as-of date."""
    hist = []
    for y in NASS_YEARS:
        try:
            _known_by(_nass_published(y), '')
        except ValueError:
            continue
        n = _nass(y)
        g, s = n['md_grain_area_harvested'] * 1000, n['md_silage_area_harvested'] * 1000
        hist.append({'year': y, 'grain_acres_harvested': _int(g), 'silage_acres_harvested': _int(s),
                     'silage_share': _pct(s / (g + s))})
    out = {'maryland_actual_nass': hist or 'No official figures published yet as of this date.'}
    try:
        t = _timeline_points()
        p = t['points'][-1]
        out['maryland_2025_outlook'] = {
            'as_of': p['as_of'], 'source': p['source'] + ' grain acres; team forecast silage acres',
            'grain_acres_harvested': _int(p['md_grain_acres']), 'silage_acres_harvested': _int(p['md_silage_acres']),
            'silage_95pct_range': f"{_int(p['md_silage_low'])} to {_int(p['md_silage_high'])}",
            'silage_share': _pct(p['md_silage_share']),
            'method': 'Team forecast from NASS reports public on that date (forecast/estimate_2025.py), not the BARC satellite model.'}
    except (ValueError, ArtifactUnavailable):
        pass
    return out


# ---------------------------------------------------------------- month-by-month outlook

def _timeline_points() -> dict:
    try:
        t = json.loads(TIMELINE.read_text(encoding='utf-8'))
    except (OSError, ValueError) as exc:
        raise ArtifactUnavailable('Market timeline (market/data/market_timeline.json) is missing; '
                                  'run python3 market/build_timeline.py.') from exc
    as_of = _AS_OF.get()
    t['points'] = [p for p in t['points'] if as_of is None or date.fromisoformat(p['as_of']) <= as_of]
    if not t['points']:
        raise ValueError(f"no {t['season']} outlook had been published as of {as_of}; the first is on {t['season']}-06-30.")
    return t


def _price_moves(supply_ratio: float, price: float) -> list[dict]:
    """Constant-elasticity price response to a supply ratio, for the assumed elasticity range."""
    out = []
    for e in ELASTICITIES:
        change = supply_ratio ** (-1 / e) - 1
