# The date a report is written "as of": tools refuse anything published after it (no hindsight).
_AS_OF: ContextVar[date | None] = ContextVar('market_as_of', default=None)


def _known_by(published: date, what: str) -> None:
    as_of = _AS_OF.get()
    if as_of is not None and published > as_of:
        raise ValueError(f'{what}: not available until {published}, so unknown as of {as_of}.')


def _nass_published(year: int) -> date:
    return date.fromisoformat(f'{year + 1}-{NASS_PUBLISHED[1]}')


