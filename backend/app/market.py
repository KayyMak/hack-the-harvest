def _verify_batch(cfg: Config, batch: list[tuple[int, str, list[str]]], sources: dict[str, str]) -> list[dict] | None:
    items = []
    for i, claim, cited in batch:
        text = '\n'.join(f'[{c}] {sources[c][:15000]}' for c in cited if c in sources)
        items.append(f'CLAIM {i}: {CITE.sub("", claim).strip()}\nCITED SOURCES:\n{text}')
    for _ in range(2):  # one retry if the reply is not the JSON we asked for
        try:
            msg = _chat(cfg, [{'role': 'system', 'content': VERIFY_SYSTEM},
                              {'role': 'user', 'content': '\n\n'.join(items)}], None)
            raw = _clean(msg.get('content'))
            results = json.loads(raw[raw.index('{'):raw.rindex('}') + 1])['results']
            if isinstance(results, list):
                return results
        except (ValueError, KeyError, TypeError):
            continue
        except MarketUnavailable:
            return None
    return None


def _verify(cfg: Config, report_claims: list[tuple[str, list[str]]], sources: dict[str, str],
            batch_size: int = 8) -> tuple[str, list[dict]]:
    """Second Nemotron pass: does each claim's cited text actually support it? Returns (status, failures)."""
    numbered = [(i, c, cited) for i, (c, cited) in enumerate(report_claims)]
    out, status = [], 'nemotron'
    for start in range(0, len(numbered), batch_size):
        batch = numbered[start:start + batch_size]
        results = _verify_batch(cfg, batch, sources)
        if results is None:
            status = 'unavailable'
            continue
        valid = {i for i, _, _ in batch}
        for r in results:
            try:
                i = int(r['i'])
            except (KeyError, TypeError, ValueError):
                continue
            if i in valid and r.get('supported') is False:
                out.append({'text': report_claims[i][0], 'kind': 'verifier',
                            'reason': 'verifier: ' + str(r.get('reason') or 'not supported by the cited source')})
    return status, out


SERIOUS = ('uncited', 'unsupported', 'verifier')
NOT_COVERED = 'Our data does not cover this.'
SECTIONS = ('bottom line', 'supply outlook', 'silage and what farmers are growing', 'price outlook',
            'how the outlook changed month to month', 'how much to trust this')


def remove_claims(markdown: str, texts: set[str]) -> str:
    """Drop the given sentences/bullets; a section left empty says our data does not cover it."""
    lines = []
    for raw in markdown.split('\n'):
        line = raw
        for t in texts:
            line = line.replace(t, '')
        stripped = re.sub(r'^\s*(?:[-*•]|\d+\.)\s*$', '', line).strip()
        if raw.strip() and not stripped:
            continue  # the whole line was removed
        lines.append(re.sub(r'\s{2,}', ' ', line).rstrip() if line != raw else line)
    out = []
    for i, line in enumerate(lines):
        heading = re.match(r'^##\s+(.*)$', line.strip())
        if heading:
            j = i + 1
            while j < len(lines) and not lines[j].strip():
                j += 1
            if j >= len(lines) or re.match(r'^#{1,6}\s', lines[j].strip()):  # empty section
                if heading.group(1).strip().lower() in SECTIONS:
                    out += [line, NOT_COVERED]
                continue  # an extra, empty heading the model added is dropped
        out.append(line)
    return '\n'.join(out).strip()


